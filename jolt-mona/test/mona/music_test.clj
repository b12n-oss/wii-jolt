(ns mona.music-test
  (:require [clojure.string :as str]
            [clojure.test :refer [deftest is run-tests]]
            [mona.music :as music]))

(deftest notes-parse-to-midi
  (is (= [{:note 60} {:note 64} {:note 67}] (music/parse-track "c4 e4 g4")))
  (is (= [{:note 61} {:note 58} {:note 108}] (music/parse-track "c#4 bb3 c8")))
  (is (= [{:note 60} {:note :hold} {:note :rest} {:note :rest} {:note :hold}]
         (music/parse-track "c4:2 -:2 ="))))

(deftest bad-tokens-throw
  (is (thrown? clojure.lang.ExceptionInfo (music/parse-track "h4")))
  (is (thrown? clojure.lang.ExceptionInfo (music/parse-track "c4:0")))
  (is (thrown? clojure.lang.ExceptionInfo (music/parse-track "c9"))))

(deftest drums-parse
  (is (= [{:drum 0} {:drum :rest} {:drum 1} {:drum 2} {:drum :rest}]
         (music/parse-drums "k - s h:2"))))

(deftest pattern-rows-must-agree
  (is (= 4 (music/pattern-rows {:p1 [:lead "c4 e4 g4 c5"] :p2 [:harm "-:4"] :tri [:bass "c2:4"] :noise "k - s -"})))
  (is (thrown? clojure.lang.ExceptionInfo
               (music/pattern-rows {:p1 [:lead "c4 e4 g4"] :p2 [:harm "-:4"] :tri [:bass "c2:4"] :noise "k - s -"}))))

(deftest the-data-validates
  (is (nil? (music/validate)))
  (is (= 16 (count music/effects)))
  (is (= (count music/effect-ids) (count music/effects)))
  (is (every? (set (keys music/songs)) [:title])))

(deftest header-has-every-id
  (let [h (music/emit-header)]
    (is (str/starts-with? h "// Generated by scripts/music-to-c"))
    (doseq [[i k] (map-indexed vector music/effect-ids)]
      (is (str/includes? h (str "#define SFX_" (str/upper-case (name k)) " " i))))
    (doseq [[i k] (map-indexed vector music/song-ids)]
      (is (str/includes? h (str "#define SONG_" (str/upper-case (name k)) " " i))))
    (is (str/includes? h "static const snd_song mona_songs[MONA_SONGS]"))
    (is (str/includes? h "#define MONA_EFFECTS 16"))
    (is (str/includes? h "#define MONA_SONGS 10"))))

(deftest header-is-stable
  (is (= (music/emit-header) (music/emit-header))))

(deftest effect-and-song-ids
  (is (= 0 (music/effect-id :jump)))
  (is (= 15 (music/effect-id :switch)))
  (is (= 7 (music/song-id :die)))
  (is (nil? (music/effect-id :nope))))

(deftest every-song-is-present-and-sized
  (doseq [k music/song-ids]
    (is (contains? music/songs k) (str k)))
  (doseq [k [:title :day :dusk :cloud :cave :castle :win]]
    (let [rows (music/song-rows k)]
      (is (<= 128 rows 256) (str k " rows " rows))
      (is (some? (:loop (music/songs k))) (str k " loops"))))
  (doseq [[k lo hi] [[:clear 16 32] [:die 4 20] [:over 16 48]]]
    (let [rows (music/song-rows k)]
      (is (<= lo rows hi) (str k " rows " rows))
      (is (nil? (:loop (music/songs k))) (str k " plays once")))))

(deftest the-die-jingle-fits-the-animation
  (is (< (music/song-seconds :die) 2.4)))

(deftest tunes-do-not-share-a-melody
  (let [melodies (into {} (map (fn [k] [k (music/melody k)]) music/song-ids))]
    (doseq [[a ma] melodies [b mb] melodies :when (not= a b)]
      (is (not= ma mb) (str a " and " b)))))

(deftest effects-are-bounded
  (doseq [[k e] (map vector music/effect-ids music/effects)]
    (is (<= 1 (count (:steps e)) 6) (str k))
    (is (< (reduce + (map (fn [[_ _ ms _]] ms) (:steps e))) 1500) (str k)))
  (is (every? zero? (map last (:steps (nth music/effects (music/effect-id :die))))) "die is silent"))

(defn -main [& _]
  (let [res (run-tests 'mona.music-test)]
    (System/exit (if (zero? (+ (:fail res 0) (:error res 0))) 0 1))))
